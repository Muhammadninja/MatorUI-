import NotificationsScreen from '@/components/screens/notifications-screen';
(globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }).IS_REACT_ACT_ENVIRONMENT = true;
beforeEach(() => { vi.clearAllMocks(); state.status = 'success'; state.unread = 1; });
async function mount() { let tree!: ReactTestRenderer; await act(async () => { tree = create(<NotificationsScreen />); }); return tree; }
test('mark-all feedback waits for confirmation, reports failure, and ignores superseded actions', async () => {
  let finish!: (ok: boolean | null) => void;
  state.markAll.mockImplementationOnce(() => new Promise<boolean | null>((resolve) => { finish = resolve; }));
  const tree = await mount();
  let pending!: Promise<void>;
  await act(async () => { pending = tree.root.findByProps({ testID: 'notifications-mark-all' }).props.onPress(); });
  expect(state.success).not.toHaveBeenCalled();
  await act(async () => { finish(false); await pending; });
  expect(state.danger).toHaveBeenCalledWith('notifications.markReadError');
  expect(state.success).not.toHaveBeenCalled();
  state.markAll.mockResolvedValueOnce(true);
  await act(async () => { await tree.root.findByProps({ testID: 'notifications-mark-all' }).props.onPress(); });
  expect(state.success).toHaveBeenCalledTimes(1);
  state.markAll.mockResolvedValueOnce(null);
  await act(async () => { await tree.root.findByProps({ testID: 'notifications-mark-all' }).props.onPress(); });
  expect(state.success).toHaveBeenCalledTimes(1); expect(state.danger).toHaveBeenCalledTimes(1);
  await act(async () => tree.unmount());
});
test('failed feed renders retry instead of the empty-notifications message', async () => {
  state.status = 'error'; state.unread = 0;
  const tree = await mount();
  expect(JSON.stringify(tree.toJSON())).toContain('notifications.loadError');
  expect(JSON.stringify(tree.toJSON())).not.toContain('notifications.emptyTitle');
  await act(async () => { tree.root.findByProps({ title: 'common.retry' }).props.onPress(); });
  expect(state.refresh).toHaveBeenCalledTimes(1);
  await act(async () => tree.unmount());
});
